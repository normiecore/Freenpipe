#!/usr/bin/env bash
# Freenpipe — local-first screen & audio memory (fork of screenpipe @ 892199f, MIT)
# https://github.com/normiecore/Freenpipe
#
# Per-session setup for a Freenpipe cloud session (Claude Code cloud VM, Ubuntu 24.04 x86_64).
# Idempotent: every step checks before it acts, so running it again is cheap.
#
#   source tools/cloud/bootstrap.sh [options]    exports into the current shell as well
#   bash tools/cloud/bootstrap.sh [options]      same work; exports only reach the env file
#
# Each Bash tool call in a Claude Code session is a fresh shell, so the exports are also written
# to ~/.freenpipe-env.sh (and to $CLAUDE_ENV_FILE when a SessionStart hook provides one).
# Start every later build or test command with:   . ~/.freenpipe-env.sh &&
#
# Options:
#   --light                env, git settings and disk check only (merger sessions)
#   --no-bun               skip `bun install` for apps/screenpipe-app-tauri
#   --fetch                also `cargo fetch` both Cargo workspaces (engine and app)
#   --quiet                less output
#   --print-setup-script   print the cloud environment setup script and exit
#                          (docs/dev/cloud-environment.md embeds its output)
#
# What it does (full mode): Rust toolchain from rust-toolchain.toml, missing apt packages (root
# only), the OpenBLAS "liblibopenblas" link, the ONNX Runtime download path, the Linux sidecars
# that pre_build.js would place, `bun install`, git settings, dev isolation (temp data dir, port
# 3035), the build environment, and a disk report that clears old build output below 8 GB free.

# Packages for the Rust workspace and the Tauri app on Ubuntu 24.04. Same list as the linux job
# of .github/workflows/freenpipe-ci.yml plus the pre_build.js extras.
FP_APT_PACKAGES="build-essential g++ cmake clang libclang-dev pkg-config curl ca-certificates \
xz-utils unzip xvfb \
ffmpeg libavformat-dev libavfilter-dev libavdevice-dev libavutil-dev \
tesseract-ocr libtesseract-dev \
libssl-dev libsqlite3-dev libbz2-dev zlib1g-dev libonig-dev \
libxdo-dev libsdl2-dev libxtst-dev libx11-dev libxext-dev libxrandr-dev \
libxinerama-dev libxcursor-dev libxi-dev libgl1-mesa-dev \
libasound2-dev libpulse-dev libpipewire-0.3-dev libdbus-1-dev \
libsamplerate-dev libwebrtc-audio-processing-dev libopenblas-dev \
libglib2.0-dev libgtk-3-dev librsvg2-dev libwebkit2gtk-4.1-dev libayatana-appindicator3-dev \
libsecret-1-dev"
FP_RUST_CHANNEL_DEFAULT="1.93.1"
FP_ORT_VERSION="1.22.0"   # must match the ort crate (2.0.0-rc.10 targets ONNX Runtime 1.22)
FP_OPENBLAS_DIR="/usr/lib/x86_64-linux-gnu/openblas"

_fp_say() { [ -n "${_fp_quiet:-}" ] || printf 'bootstrap: %s\n' "$*"; }
_fp_warn() { printf 'bootstrap: WARNING: %s\n' "$*" >&2; }

_fp_as_root() {
  if [ "$(id -u)" = "0" ]; then "$@"
  elif command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then sudo -n "$@"
  else return 1
  fi
}

_fp_print_setup_script() {
  local pk tc chan targets="" t
  tc="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/rust-toolchain.toml"
  chan="$(sed -n 's/^channel *= *"\([^"]*\)".*/\1/p' "$tc" 2>/dev/null)"
  chan="${chan:-$FP_RUST_CHANNEL_DEFAULT}"
  for t in $(sed -n 's/^targets *= *\[\(.*\)\].*/\1/p' "$tc" 2>/dev/null | tr ',' ' ' | tr -d '"'); do
    targets="$targets -t $t"
  done
  targets="${targets:- -t x86_64-unknown-linux-gnu}"
  # shellcheck disable=SC2086
  pk="$(printf '%s\n' $FP_APT_PACKAGES | awk '
    { if (len > 0 && len + length($0) + 1 > 92) { printf " \\\n"; len = 0 }
      if (len == 0) { printf "    %s", $0; len = 4 + length($0) } else { printf " %s", $0; len += 1 + length($0) } }
    END { printf "\n" }')"
  cat <<EOF
#!/bin/bash
# Freenpipe cloud environment setup (runs as root on Ubuntu 24.04, before Claude Code starts).
# Generated by: bash tools/cloud/bootstrap.sh --print-setup-script
# Keep it under ~5 minutes so the environment snapshot is cached. It never fails the session:
# tools/cloud/bootstrap.sh repeats any step that did not complete here.
export DEBIAN_FRONTEND=noninteractive

install_apt() {
  apt-get update -qq || return 1
  apt-get install -y -qq --no-install-recommends \\
$pk || return 1
  # antirez-asr-sys links "-llibopenblas" (double lib prefix); give the linker that name.
  mkdir -p $FP_OPENBLAS_DIR/lib
  ln -sf /usr/lib/x86_64-linux-gnu/libopenblas.so $FP_OPENBLAS_DIR/lib/liblibopenblas.so
  ln -sf /usr/lib/x86_64-linux-gnu/libopenblas.a $FP_OPENBLAS_DIR/lib/liblibopenblas.a
  if [ -d /usr/include/x86_64-linux-gnu/openblas-pthread ]; then
    ln -sfn /usr/include/x86_64-linux-gnu/openblas-pthread $FP_OPENBLAS_DIR/include
  fi
}

install_rust() {
  # Toolchain, components and targets exactly as rust-toolchain.toml pins them, so no session
  # downloads them again. rustup-init comes from static.rust-lang.org (on the Trusted list).
  export PATH="\$HOME/.cargo/bin:\$PATH"
  if ! command -v rustup >/dev/null 2>&1; then
    curl -fsSL -o /tmp/rustup-init https://static.rust-lang.org/rustup/dist/x86_64-unknown-linux-gnu/rustup-init &&
      chmod +x /tmp/rustup-init && /tmp/rustup-init -y --profile minimal --default-toolchain none || return 1
  fi
  rustup toolchain install $chan --profile minimal -c rustfmt -c clippy \\
   $targets
}

install_apt > /tmp/fp-setup-apt.log 2>&1 &
apt_pid=\$!
install_rust > /tmp/fp-setup-rust.log 2>&1 || echo "rust toolchain install failed (bootstrap.sh retries)"
wait \$apt_pid || { echo "apt install failed (bootstrap.sh retries)"; tail -n 20 /tmp/fp-setup-apt.log; }
exit 0
EOF
}

_fp_disk_check_src='
fp_disk_check() {
  # fp_disk_check [MIN_GB]: report free disk; below MIN_GB (default 8) free old build output.
  local min="${1:-8}" dir="${CARGO_TARGET_DIR:-$HOME}" avail
  while [ ! -e "$dir" ] && [ "$dir" != "/" ] && [ "$dir" != "." ]; do dir="$(dirname "$dir")"; done
  avail=$(df -Pk "$dir" 2>/dev/null | awk "NR==2 {print int(\$4/1048576)}")
  [ -n "$avail" ] || { echo "disk: cannot read free space"; return 0; }
  echo "disk: ${avail} GB free on $(df -P "$dir" | awk "NR==2 {print \$6}") (threshold ${min} GB)"
  [ "$avail" -lt "$min" ] || return 0
  echo "disk: below ${min} GB, clearing old build output"
  if [ -n "${CARGO_TARGET_DIR:-}" ] && [ -d "$CARGO_TARGET_DIR" ]; then
    rm -rf "$CARGO_TARGET_DIR"/*/incremental "$CARGO_TARGET_DIR"/*/*/incremental 2>/dev/null
    rm -rf "$CARGO_TARGET_DIR"/release "$CARGO_TARGET_DIR"/release-dev "$CARGO_TARGET_DIR"/*/release-dev 2>/dev/null
  fi
  rm -rf "$HOME/.bun/install/cache" "$HOME/.cargo/registry/cache" 2>/dev/null
  avail=$(df -Pk "$dir" | awk "NR==2 {print int(\$4/1048576)}")
  if [ "$avail" -lt "$min" ] && [ -n "${CARGO_TARGET_DIR:-}" ]; then
    echo "disk: still ${avail} GB, removing the whole target dir $CARGO_TARGET_DIR"
    rm -rf "$CARGO_TARGET_DIR"
  fi
  echo "disk: now $(df -Pk "$dir" | awk "NR==2 {print int(\$4/1048576)}") GB free"
}
'

_fp_bootstrap_main() {
  local light="" no_bun="" do_fetch="" a
  _fp_quiet=""
  for a in "$@"; do
    case "$a" in
      --light) light=1 ;;
      --no-bun) no_bun=1 ;;
      --fetch) do_fetch=1 ;;
      --quiet) _fp_quiet=1 ;;
      --print-setup-script) _fp_print_setup_script; return 0 ;;
      -h|--help) sed -n '2,30p' "${BASH_SOURCE[0]}"; return 0 ;;
      *) _fp_warn "unknown option $a"; return 2 ;;
    esac
  done

  local root
  root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)" || return 1
  if [ ! -f "$root/Cargo.toml" ] || [ ! -f "$root/rust-toolchain.toml" ]; then
    _fp_warn "cannot find the repository root from ${BASH_SOURCE[0]}"
    return 1
  fi
  local state="${FP_STATE:-$HOME/.cache/freenpipe}"
  mkdir -p "$state" || return 1
  local app="$root/apps/screenpipe-app-tauri"
  local envf="$HOME/.freenpipe-env.sh"
  local exports=()
  _fp_export() { exports+=("export $1=$(printf '%q' "$2")"); export "$1=$2"; }

  # ---- build environment -------------------------------------------------------------------
  _fp_export FP_ROOT "$root"
  _fp_export FP_STATE "$state"
  _fp_export CARGO_TARGET_DIR "${CARGO_TARGET_DIR:-$state/target}"
  _fp_export CARGO_PROFILE_DEV_DEBUG 0
  _fp_export CARGO_PROFILE_TEST_DEBUG 0
  _fp_export CARGO_PROFILE_RELEASE_DEV_DEBUG 0
  # .cargo/config.toml asks for 16 jobs; the VM has 4 vCPUs and 16 GB.
  _fp_export CARGO_BUILD_JOBS "${CARGO_BUILD_JOBS:-4}"
  _fp_export CARGO_NET_GIT_FETCH_WITH_CLI true
  _fp_export CARGO_TERM_COLOR never
  [ -d "$HOME/.cargo/bin" ] && case ":$PATH:" in *":$HOME/.cargo/bin:"*) ;; *) _fp_export PATH "$HOME/.cargo/bin:$PATH" ;; esac

  # ---- dev isolation (CLAUDE.md, PLAN.md section 2.4): never ~/.screenpipe, never 3030/11435 --
  _fp_export FP_DD "${FP_DD:-$state/dev-data}"
  _fp_export SCREENPIPE_DATA_DIR "$FP_DD"
  _fp_export FP_PORT "${FP_PORT:-3035}"
  _fp_export SCREENPIPE_PORT "$FP_PORT"
  _fp_export SCREENPIPE_FOCUS_PORT "${SCREENPIPE_FOCUS_PORT:-11436}"
  _fp_export SCREENPIPE_API_KEY "${SCREENPIPE_API_KEY:-fp-dev-key}"
  case "$FP_PORT" in 3030|11435) _fp_warn "FP_PORT=$FP_PORT is a screenpipe port; use 3035"; return 1 ;; esac
  case "$(readlink -m "$FP_DD")/" in "$(readlink -m "$HOME/.screenpipe")"/*)
    _fp_warn "FP_DD points into ~/.screenpipe; refusing"; return 1 ;; esac
  mkdir -p "$FP_DD"

  # ---- git settings ---------------------------------------------------------------------------
  git -C "$root" config rerere.enabled true
  git -C "$root" config merge.conflictstyle zdiff3
  git -C "$root" config pull.ff only
  if [ -z "$(git -C "$root" config user.email)" ]; then
    _fp_warn "git user.email is not set; commits need an identity (the cloud harness normally sets it)"
  fi

  if [ -z "$light" ]; then
    # ---- Rust toolchain (rust-toolchain.toml) -------------------------------------------------
    local chan
    chan="$(sed -n 's/^channel *= *"\([^"]*\)".*/\1/p' "$root/rust-toolchain.toml")"
    chan="${chan:-$FP_RUST_CHANNEL_DEFAULT}"
    if command -v rustup >/dev/null 2>&1; then
      if rustup toolchain list 2>/dev/null | grep -q "^$chan"; then
        _fp_say "rust $chan present"
      else
        _fp_say "installing rust $chan (rust-toolchain.toml)"
        local targets="" t
        for t in $(sed -n 's/^targets *= *\[\(.*\)\].*/\1/p' "$root/rust-toolchain.toml" | tr ',' ' ' | tr -d '"'); do
          targets="$targets -t $t"
        done
        # shellcheck disable=SC2086
        rustup toolchain install "$chan" --profile minimal -c rustfmt -c clippy $targets \
          || _fp_warn "rustup could not install $chan"
      fi
    elif command -v cargo >/dev/null 2>&1; then
      _fp_warn "rustup missing; using $(cargo --version 2>/dev/null) instead of the pinned $chan"
    else
      _fp_warn "no Rust toolchain found (rustup and cargo missing)"
    fi

    # ---- system packages (normally installed by the environment setup script) --------------
    local missing="" p
    for p in libwebkit2gtk-4.1-dev libopenblas-dev libtesseract-dev libavdevice-dev libpipewire-0.3-dev \
             libclang-dev libsamplerate-dev libwebrtc-audio-processing-dev libsecret-1-dev tesseract-ocr ffmpeg; do
      dpkg -s "$p" >/dev/null 2>&1 || missing="$missing $p"
    done
    if [ -n "$missing" ]; then
      _fp_say "missing apt packages:$missing (the environment setup script did not finish?)"
      # shellcheck disable=SC2086
      if _fp_as_root env DEBIAN_FRONTEND=noninteractive apt-get update -qq >/dev/null 2>&1 &&
         _fp_as_root env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends \
           $FP_APT_PACKAGES >"$state/apt.log" 2>&1; then
        _fp_say "apt packages installed"
      else
        _fp_warn "apt install failed or no root; see $state/apt.log. Native crates may not build."
      fi
    fi

    # ---- OpenBLAS: antirez-asr-sys links -llibopenblas -------------------------------------------
    if [ ! -e "$FP_OPENBLAS_DIR/lib/liblibopenblas.so" ] && [ -e /usr/lib/x86_64-linux-gnu/libopenblas.so ]; then
      _fp_as_root mkdir -p "$FP_OPENBLAS_DIR/lib" &&
      _fp_as_root ln -sf /usr/lib/x86_64-linux-gnu/libopenblas.so "$FP_OPENBLAS_DIR/lib/liblibopenblas.so" &&
      _fp_as_root ln -sf /usr/lib/x86_64-linux-gnu/libopenblas.a "$FP_OPENBLAS_DIR/lib/liblibopenblas.a" ||
        _fp_warn "could not create the liblibopenblas links (no root)"
    fi
    if [ ! -e "$FP_OPENBLAS_DIR/include" ] && [ -d /usr/include/x86_64-linux-gnu/openblas-pthread ]; then
      _fp_as_root ln -sfn /usr/include/x86_64-linux-gnu/openblas-pthread "$FP_OPENBLAS_DIR/include" || true
    fi
    if [ -e "$FP_OPENBLAS_DIR/lib/liblibopenblas.so" ]; then
      _fp_export OPENBLAS_PATH "$FP_OPENBLAS_DIR"
    else
      _fp_warn "OpenBLAS link missing; screenpipe-audio (qwen3-asr) will not link"
    fi

    # ---- ONNX Runtime: the ort crate downloads it from cdn.pyke.io at build time on Linux ----
    if [ ! -f "$state/ort-mode" ]; then
      # Probe the exact archive ort-sys 2.0.0-rc.10 downloads. A blocked host answers 403 from the
      # session proxy (x-deny-reason: host_not_allowed) or fails to connect.
      local code
      code="$(curl -sS -o /dev/null -L -r 0-0 --max-time 20 -w '%{http_code}' \
        "https://cdn.pyke.io/0/pyke:ort-rs/ms@$FP_ORT_VERSION/x86_64-unknown-linux-gnu.tgz" 2>/dev/null)"
      case "$code" in 200|206) echo download > "$state/ort-mode" ;; *) echo github > "$state/ort-mode" ;; esac
    fi
    if [ "$(cat "$state/ort-mode")" = "github" ]; then
      # cdn.pyke.io is not on the allowlist: link the official GitHub release dynamically instead.
      local ortdir="$state/onnxruntime-linux-x64-$FP_ORT_VERSION"
      if [ ! -e "$ortdir/lib/libonnxruntime.so" ]; then
        _fp_say "cdn.pyke.io unreachable; fetching ONNX Runtime $FP_ORT_VERSION from GitHub releases"
        curl -fsSL --max-time 300 -o "$state/ort.tgz" \
          "https://github.com/microsoft/onnxruntime/releases/download/v$FP_ORT_VERSION/onnxruntime-linux-x64-$FP_ORT_VERSION.tgz" &&
          tar -xzf "$state/ort.tgz" -C "$state" && rm -f "$state/ort.tgz" ||
          _fp_warn "ONNX Runtime download failed; add cdn.pyke.io to the network allowlist (docs/dev/cloud-environment.md)"
      fi
      if [ -e "$ortdir/lib/libonnxruntime.so" ]; then
        _fp_export ORT_LIB_LOCATION "$ortdir/lib"
        _fp_export ORT_PREFER_DYNAMIC_LINK 1
        _fp_export LD_LIBRARY_PATH "$ortdir/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
      fi
    fi

    # ---- Linux sidecars that pre_build.js would place (it downloads from hosts not on the list) --
    local tauri="$app/src-tauri"
    if [ -d "$tauri" ]; then
      if [ ! -e "$tauri/ffmpeg/ffmpeg" ] && command -v ffmpeg >/dev/null 2>&1; then
        mkdir -p "$tauri/ffmpeg"
        ln -sf "$(command -v ffmpeg)" "$tauri/ffmpeg/ffmpeg"
        command -v ffprobe >/dev/null 2>&1 && ln -sf "$(command -v ffprobe)" "$tauri/ffmpeg/ffprobe"
      fi
      if [ ! -e "$tauri/tesseract" ] && command -v tesseract >/dev/null 2>&1; then
        ln -sf "$(command -v tesseract)" "$tauri/tesseract"
      fi
      if [ ! -e "$tauri/bun-x86_64-unknown-linux-gnu" ] && command -v bun >/dev/null 2>&1; then
        cp "$(command -v bun)" "$tauri/bun-x86_64-unknown-linux-gnu" && chmod +x "$tauri/bun-x86_64-unknown-linux-gnu"
      fi
      # The app crate embeds ../out at compile time; CI uses the same placeholder when the
      # frontend build is missing. A real `bun run build` replaces it.
      if [ ! -e "$app/out/index.html" ]; then
        mkdir -p "$app/out" && printf '<!doctype html><title>placeholder</title>\n' > "$app/out/index.html"
      fi
    fi

    # ---- frontend dependencies ---------------------------------------------------------------
    if [ -z "$no_bun" ] && [ -f "$app/package.json" ]; then
      if ! command -v bun >/dev/null 2>&1; then
        _fp_warn "bun not found; frontend checks run in CI only"
      else
        local lockhash marker="$state/bun-install.ok"
        lockhash="$(cat "$app/bun.lock" "$app/package.json" 2>/dev/null | sha256sum | cut -c1-16)"
        if [ -d "$app/node_modules" ] && [ "$(cat "$marker" 2>/dev/null)" = "$lockhash" ]; then
          _fp_say "node_modules up to date"
        else
          _fp_say "bun install in apps/screenpipe-app-tauri (bun $(bun --version 2>/dev/null))"
          local ca="${SSL_CERT_FILE:-/etc/ssl/certs/ca-certificates.crt}"
          if (cd "$app" && timeout 900 bun install --frozen-lockfile >"$state/bun-install.log" 2>&1) ||
             (cd "$app" && NODE_EXTRA_CA_CERTS="$ca" NODE_USE_SYSTEM_CA=1 \
                timeout 900 bun install --frozen-lockfile >>"$state/bun-install.log" 2>&1) ||
             (cd "$app" && NODE_EXTRA_CA_CERTS="$ca" \
                timeout 900 bun install --frozen-lockfile --cafile "$ca" >>"$state/bun-install.log" 2>&1); then
            echo "$lockhash" > "$marker"
            _fp_say "bun install done"
          else
            _fp_warn "bun install failed (log: $state/bun-install.log). Bun has known issues with the cloud" \
                     "proxy; frontend build and tests then run only in CI."
            tail -n 5 "$state/bun-install.log" >&2
          fi
        fi
      fi
    fi

    # ---- optional: pre-fetch crates (downloads only, no compile) ----------------------------
    if [ -n "$do_fetch" ]; then
      _fp_say "cargo fetch (engine workspace)"
      (cd "$root" && timeout 900 cargo fetch --locked >"$state/cargo-fetch.log" 2>&1) ||
        _fp_warn "cargo fetch (engine) failed; see $state/cargo-fetch.log"
      _fp_say "cargo fetch (app workspace)"
      (cd "$root" && timeout 900 cargo fetch --locked --manifest-path "$tauri/Cargo.toml" >>"$state/cargo-fetch.log" 2>&1) ||
        _fp_warn "cargo fetch (app) failed; see $state/cargo-fetch.log"
    fi
  fi

  # ---- env file for later shells ------------------------------------------------------------
  {
    echo "# Generated by tools/cloud/bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Source it: . ~/.freenpipe-env.sh"
    printf '%s\n' "${exports[@]}"
    printf '%s\n' "$_fp_disk_check_src"
  } > "$envf"
  if [ -n "${CLAUDE_ENV_FILE:-}" ]; then
    printf '. %q\n' "$envf" >> "$CLAUDE_ENV_FILE"
  fi
  eval "$_fp_disk_check_src"

  # ---- summary ------------------------------------------------------------------------------
  if [ -z "$_fp_quiet" ]; then
    echo "bootstrap: repo $root ($(git -C "$root" rev-parse --abbrev-ref HEAD 2>/dev/null) at $(git -C "$root" rev-parse --short HEAD 2>/dev/null))"
    echo "bootstrap: rust $(rustc --version 2>/dev/null | cut -d' ' -f2) | bun $(bun --version 2>/dev/null || echo none) | python $(python3 --version 2>/dev/null | cut -d' ' -f2) | gh $(gh --version 2>/dev/null | head -n1 | cut -d' ' -f3)"
    echo "bootstrap: CARGO_TARGET_DIR=$CARGO_TARGET_DIR  FP_DD=$FP_DD  FP_PORT=$FP_PORT  OPENBLAS_PATH=${OPENBLAS_PATH:-unset}  ort=$(cat "$state/ort-mode" 2>/dev/null || echo n/a)"
    if [ -d "$CARGO_TARGET_DIR" ]; then
      echo "bootstrap: target dir uses $(du -sh "$CARGO_TARGET_DIR" 2>/dev/null | cut -f1)"
    fi
    echo "bootstrap: env written to $envf; start later commands with: . ~/.freenpipe-env.sh &&"
  fi
  fp_disk_check 8
  return 0
}

_fp_bootstrap_main "$@"
_fp_rc=$?
unset -f _fp_bootstrap_main _fp_print_setup_script _fp_as_root _fp_export _fp_say _fp_warn
unset _fp_quiet _fp_disk_check_src FP_APT_PACKAGES FP_RUST_CHANNEL_DEFAULT FP_ORT_VERSION FP_OPENBLAS_DIR
if [ "${BASH_SOURCE[0]}" = "$0" ]; then exit "$_fp_rc"; fi
return "$_fp_rc" 2>/dev/null || true
